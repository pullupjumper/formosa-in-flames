"""Generate the control panel's TypeScript types from the UI contract block in schema.lua.

The block sits between UI_CONTRACT_BEGIN and UI_CONTRACT_END. Every type the
block names must be declared inside it or listed in EXTERNAL_TYPES; anything
else is an error, never a guess.

Usage:
  python3 tools/gen_ui_types.py           # write htmls-app/src/types/generated.ts
  python3 tools/gen_ui_types.py --check   # exit 1 when the file is stale
"""

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import List, Optional

ROOT = Path(__file__).resolve().parent.parent
SCHEMA_PATH = ROOT / "src" / "core" / "schema.lua"
OUTPUT_PATH = ROOT / "htmls-app" / "src" / "types" / "generated.ts"

BEGIN_MARKER = "-- UI_CONTRACT_BEGIN"
END_MARKER = "-- UI_CONTRACT_END"
LUA_PREFIX = "SBJ__"

PRIMITIVES = {"string": "string", "number": "number", "integer": "number", "boolean": "boolean"}
EXTERNAL_TYPES = {"CMO__Location": "Coordinate", "CMO__Waypoint": "Coordinate", "SBJ__C2TypeKey": "string"}
EXTERNAL_IMPORTS = {"Coordinate": "@/types/geo"}

HEADER = """// Generated by tools/gen_ui_types.py from the UI contract block in src/core/schema.lua.
// Do not edit by hand: change schema.lua and run `python3 tools/gen_ui_types.py`.
"""


class ContractError(Exception):
    pass


@dataclass
class Field:
    name: str
    lua_type: str
    optional: bool
    doc: str


@dataclass
class Decl:
    name: str
    doc: List[str]
    parent: Optional[str] = None
    alias_type: Optional[str] = None
    fields: List[Field] = field(default_factory=list)


def extract_block(text: str) -> List[str]:
    lines = text.splitlines()
    starts = [i for i, line in enumerate(lines) if line.strip() == BEGIN_MARKER]
    ends = [i for i, line in enumerate(lines) if line.strip() == END_MARKER]
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise ContractError(f"schema.lua needs exactly one {BEGIN_MARKER} ... {END_MARKER} block")
    return lines[starts[0] + 1:ends[0]]


def split_type_and_doc(rest: str):
    """Split `<type> <doc>` where the type may hold spaces inside brackets."""
    depth = 0
    for i, ch in enumerate(rest):
        if ch in "<({":
            depth += 1
        elif ch in ">)}":
            depth -= 1
        elif ch == " " and depth == 0:
            if rest[i - 1] in "|," or rest[i + 1:i + 2] in ("|", ""):
                continue
            return rest[:i], rest[i + 1:].strip()
    return rest, ""


def parse_block(lines: List[str]) -> List[Decl]:
    decls: List[Decl] = []
    doc: List[str] = []
    current: Optional[Decl] = None

    for number, raw in enumerate(lines, 1):
        line = raw.strip()
        class_match = re.match(r"^---@class\s+(\w+)(?:\s*:\s*([\w.]+))?\s*$", line)
        alias_match = re.match(r"^---@alias\s+(\w+)\s+(.+)$", line)
        field_match = re.match(r"^---@field\s+(\w+)(\??)\s+(.+)$", line)

        if class_match:
            current = Decl(class_match.group(1), doc, parent=class_match.group(2))
            decls.append(current)
            doc = []
        elif alias_match:
            lua_type, _ = split_type_and_doc(alias_match.group(2))
            decls.append(Decl(alias_match.group(1), doc, alias_type=lua_type))
            current, doc = None, []
        elif field_match:
            if current is None:
                raise ContractError(f"block line {number}: @field outside a @class")
            lua_type, field_doc = split_type_and_doc(field_match.group(3))
            current.fields.append(Field(field_match.group(1), lua_type, field_match.group(2) == "?", field_doc))
        elif line.startswith("---@"):
            raise ContractError(f"block line {number}: unsupported annotation `{line}`")
        elif line.startswith("---"):
            doc.append(line[3:].strip())
            current = None
        else:
            current, doc = None, []

    return decls


class TypeParser:
    """Recursive descent over a LuaLS type expression, emitting TypeScript."""

    TOKEN = re.compile(r'\s*(table<|[<>{}(),:|?]|\[\]|"[^"]*"|[\w.]+)')

    def __init__(self, text: str, known: set):
        self.tokens = []
        pos = 0
        while pos < len(text):
            match = self.TOKEN.match(text, pos)
            if not match or match.end() == pos:
                raise ContractError(f"cannot read type `{text}`")
            self.tokens.append(match.group(1))
            pos = match.end()
        self.text = text
        self.known = known
        self.index = 0

    def peek(self):
        return self.tokens[self.index] if self.index < len(self.tokens) else None

    def take(self, expected=None):
        token = self.peek()
        if token is None or (expected is not None and token != expected):
            raise ContractError(f"expected `{expected}` in type `{self.text}`")
        self.index += 1
        return token

    def parse(self):
        result = self.union()
        if self.peek() is not None:
            raise ContractError(f"unexpected `{self.peek()}` in type `{self.text}`")
        return result

    def union(self):
        parts = [self.postfix()]
        while self.peek() == "|":
            self.take("|")
            parts.append(self.postfix())
        kept = [part for part in parts if part != "nil"]
        if len(kept) != len(parts):
            kept.append("undefined")
        return " | ".join(kept)

    def postfix(self):
        result = self.atom()
        while self.peek() == "[]":
            self.take("[]")
            result = f"({result})[]" if " " in result else f"{result}[]"
        return result

    def atom(self):
        token = self.take()
        if token == "(":
            inner = self.union()
            self.take(")")
            return inner
        if token == "table<":
            key = self.union()
            self.take(",")
            value = self.union()
            self.take(">")
            if key == "number":
                return f"({value})[]" if " " in value else f"{value}[]"
            return f"Record<{key}, {value}>"
        if token == "{":
            members = []
            while self.peek() != "}":
                name = self.take()
                optional = self.peek() == "?"
                if optional:
                    self.take("?")
                self.take(":")
                members.append(f"{name}{'?' if optional else ''}: {self.union()}")
                if self.peek() == ",":
                    self.take(",")
            self.take("}")
            return "{ " + "; ".join(members) + " }"
        if token.startswith('"'):
            return "'" + token[1:-1] + "'"
        if token == "nil":
            return "nil"
        if token in PRIMITIVES:
            return PRIMITIVES[token]
        if token in EXTERNAL_TYPES:
            return EXTERNAL_TYPES[token]
        if token in self.known:
            return ts_name(token)
        raise ContractError(f"type `{token}` is neither in the UI contract block nor in EXTERNAL_TYPES")


def ts_name(lua_name: str) -> str:
    if not lua_name.startswith(LUA_PREFIX):
        raise ContractError(f"`{lua_name}` must start with {LUA_PREFIX}")
    return lua_name[len(LUA_PREFIX):]


def format_doc(lines: List[str], indent: str) -> List[str]:
    if not lines:
        return []
    if len(lines) == 1:
        return [f"{indent}/** {lines[0]} */"]
    return [f"{indent}/**"] + [f"{indent} * {line}" for line in lines] + [f"{indent} */"]


def render(decls: List[Decl]) -> str:
    known = {decl.name for decl in decls}
    body: List[str] = []

    for decl in decls:
        body.append("")
        body.extend(format_doc(decl.doc, ""))
        if decl.alias_type is not None:
            body.append(f"export type {ts_name(decl.name)} = {TypeParser(decl.alias_type, known).parse()};")
            continue
        # A parent outside the block only matters to LuaLS, so the page gets just the fields written here
        extends = f" extends {ts_name(decl.parent)}" if decl.parent in known else ""
        body.append(f"export interface {ts_name(decl.name)}{extends} {{")
        for f in decl.fields:
            ts_type = TypeParser(f.lua_type, known).parse()
            optional = f.optional
            if ts_type.endswith(" | undefined"):
                ts_type, optional = ts_type[: -len(" | undefined")], True
            body.extend(format_doc([f.doc] if f.doc else [], "  "))
            body.append(f"  {f.name}{'?' if optional else ''}: {ts_type};")
        body.append("}")

    text = "\n".join(body)
    imports = []
    for ts_type, module in sorted(EXTERNAL_IMPORTS.items()):
        if re.search(rf"\b{ts_type}\b", text):
            imports.append(f"import type {{ {ts_type} }} from '{module}';")
    return HEADER + ("\n" + "\n".join(imports) + "\n" if imports else "") + text + "\n"


def generate(schema_text: str) -> str:
    return render(parse_block(extract_block(schema_text)))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when the generated file is stale")
    args = parser.parse_args()

    try:
        output = generate(SCHEMA_PATH.read_text(encoding="utf-8"))
    except ContractError as error:
        print(f"gen_ui_types: {error}", file=sys.stderr)
        return 1

    current = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.exists() else None
    if args.check:
        if current != output:
            print(f"gen_ui_types: {OUTPUT_PATH.relative_to(ROOT)} is stale; run python3 tools/gen_ui_types.py",
                  file=sys.stderr)
            return 1
        return 0

    if current != output:
        OUTPUT_PATH.write_text(output, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
